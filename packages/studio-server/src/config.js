import { config } from 'dotenv';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import crypto from 'node:crypto';
import fs from 'node:fs';
import { envFilePath } from './storage.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const envPath = envFilePath;

const readPackage = (packagePath) => {
  try { return JSON.parse(fs.readFileSync(packagePath, 'utf8')); }
  catch { return null; }
};
const rootPackage = readPackage(resolve(__dirname, '../../../package.json'));
const serverPackage = readPackage(resolve(__dirname, '../package.json'));
const chezcordPackage = readPackage(resolve(__dirname, '../../chezcord/package.json'));

if (fs.existsSync(envPath)) {
  config({ path: envPath });
}

const PORT = parseInt(process.env.PORT || '3000', 10);
const HOST = process.env.HOST || '127.0.0.1';
const showBotTokenExportOptionToAuthorizedUsers = ['1', 'true', 'yes', 'on'].includes(String(process.env.ARC_SHOW_BOT_TOKEN_EXPORT_OPTION || '').trim().toLowerCase());

let setupKey = process.env.ARC_SETUP_KEY?.trim() || 'ARC-CHANGETHIS';
let isDefaultKey = setupKey === 'ARC-CHANGETHIS';

let sessionSecret = process.env.SESSION_SECRET?.trim();
let wasSecretAutoGenerated = false;

if (!sessionSecret || sessionSecret === 'ARC-SESSIONSECRET' || sessionSecret === 'arc_default_session_secret_2026') {
  sessionSecret = crypto.randomBytes(32).toString('hex');
  wasSecretAutoGenerated = true;

  try {
    const exampleEnvPath = resolve(__dirname, '../../../.env.example');
    let envContent = '';

    if (fs.existsSync(envPath)) {
      envContent = fs.readFileSync(envPath, 'utf8');
      if (envContent.includes('SESSION_SECRET=')) {
        envContent = envContent.replace(
          /SESSION_SECRET=.*$/m,
          `SESSION_SECRET=${sessionSecret}`
        );
      } else {
        envContent += `\nSESSION_SECRET=${sessionSecret}\n`;
      }
    } else if (!process.env.ARC_ENV_FILE && fs.existsSync(exampleEnvPath)) {
      envContent = fs.readFileSync(exampleEnvPath, 'utf8');
      envContent = envContent.replace(
        /SESSION_SECRET=.*$/m,
        `SESSION_SECRET=${sessionSecret}`
      );
    } else {
      envContent = `# Arc Studio Server Configuration\nPORT=${PORT}\nHOST=${HOST}\nARC_SETUP_KEY=${setupKey}\nSESSION_SECRET=${sessionSecret}\nLOG_RETENTION_DAYS=7\n`;
    }

    fs.mkdirSync(dirname(envPath), { recursive: true });
    fs.writeFileSync(envPath, envContent, { encoding: 'utf8', mode: 0o600 });
  } catch (err) {
    console.error('[Config] Failed to persist generated SESSION_SECRET to .env:', err.message);
  }
}

let botTokenEncryptionKey = process.env.ARC_BOT_TOKEN_ENCRYPTION_KEY?.trim();
if (!botTokenEncryptionKey) {
  const generatedKey = crypto.randomBytes(32).toString('hex');
  try {
    let envContent = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
    if (/^ARC_BOT_TOKEN_ENCRYPTION_KEY=.*$/m.test(envContent)) {
      envContent = envContent.replace(/^ARC_BOT_TOKEN_ENCRYPTION_KEY=.*$/m, `ARC_BOT_TOKEN_ENCRYPTION_KEY=${generatedKey}`);
    } else {
      envContent = `${envContent.replace(/\s*$/, '')}\nARC_BOT_TOKEN_ENCRYPTION_KEY=${generatedKey}\n`;
    }
    fs.mkdirSync(dirname(envPath), { recursive: true });
    fs.writeFileSync(envPath, envContent, { encoding: 'utf8', mode: 0o600 });
    try { fs.chmodSync(envPath, 0o600); } catch {}
    botTokenEncryptionKey = generatedKey;
  } catch (err) {
    console.error('[Config] Could not persist the bot-token encryption key; using the session secret as fallback:', err.message);
    botTokenEncryptionKey = sessionSecret;
  }
}
//
export const serverConfig = {
  desktopMode: process.env.ARC_DESKTOP_MODE === '1',
  desktopDevMode: process.env.ARC_DESKTOP_DEV_MODE === '1',
  port: PORT,
  host: HOST,
  showBotTokenExportOptionToAuthorizedUsers,
  setupKey,
  isDefaultKey,
  sessionSecret,
  botTokenEncryptionKey,
  wasSecretAutoGenerated,
  defaultBotToken: process.env.DISCORD_BOT_TOKEN?.trim() || null,
  version: rootPackage?.version || serverPackage?.version || 'unknown',
  chezcordVersion: chezcordPackage?.version || 'unknown'
};
